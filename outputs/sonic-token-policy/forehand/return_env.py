"""Front-fed physical ball return through a reference encoder and frozen SONIC.

Policy parameters modify a reference trajectory, never actuator positions.
Every robot torque target is generated by the unchanged SONIC decoder.
"""
from scipy.optimize import least_squares
from scipy.ndimage import gaussian_filter1d
from common import *
NEAR,NET,FAR,WIDTH,TOP= .36,1.73,3.10,1.525,.76
RETURN_DIR=HERE/'runs/return-v1'
PARAM_NAMES=['shoulder_pitch','shoulder_roll','shoulder_yaw','elbow','wrist_roll','wrist_pitch','wrist_yaw','phase_lead_s','swing_time_scale']
# The wrist is free to choose a useful face angle; the old 45-degree normal is not rewarded.
PARAM_SCALE=np.array([.45,.30,.40,.45,.80,.60,.70,.16,.18])

def corrected_reference(output):
    m=next(m for m in motions() if m['name']=='table_tennis_forehand_y+000_z010');e=make_env(m);q0=m['dof'].copy();q=q0.copy()
    joint_ids=e.model.actuator_trnid[e.body_act[22:],0];bounds=e.model.jnt_range[joint_ids].copy();bounds[:,0]+=.015;bounds[:,1]-=.015
    for i,t in enumerate(m['time']):
        # Initialization only: rotate the forehand face toward the opponent.
        blend=np.exp(-.5*((t-1.)/.33)**4)
        nr=m['wrist_rotation'][i,:,1];desired=(1-blend)*nr+blend*np.array([1.,0.,.04]);desired/=np.linalg.norm(desired)
        e.data.qpos[e.bqa]=q0[i];e.data.qpos[:3]=m['root_pos'][i]
        def residual(a):
            e.data.qpos[e.bqa[22:]]=a;mujoco.mj_forward(e.model,e.data)
            return np.r_[(face(e)-m['actual_contact_pos'][i])*12,
                         (e.data.xmat[e.wrist].reshape(3,3)[:,1]-desired)*2,.07*(a-q0[i,22:])]
        fit=least_squares(residual,np.clip(q0[i,22:],bounds[:,0],bounds[:,1]),bounds=(bounds[:,0],bounds[:,1]),max_nfev=70)
        q[i,22:]=fit.x
    q[:,22:]=gaussian_filter1d(q[:,22:],1.,axis=0,mode='nearest');q[-1]=q[0]
    output.mkdir(parents=True,exist_ok=True)
    np.savez_compressed(output/'forward_reference.npz',q=q,time=m['time'],source_q=q0)
    return q

def sample_cases(rng,n,wide=False):
    # Same front serve distribution for all candidates; held-out RNG is separate.
    scale=2 if wide else 1
    return [dict(y_m=float(y),vx_m_s=float(vx),vz_m_s=float(vz),z_m=1.15)
        for y,vx,vz in zip(rng.uniform(-.38-.018*scale,-.38+.018*scale,n),
            rng.uniform(-2.5-.06*scale,-2.5+.06*scale,n),rng.uniform(2.086-.04*scale,2.086+.04*scale,n))]
NOMINAL=dict(y_m=-.38,vx_m_s=-2.5,vz_m_s=2.086,z_m=1.15)

class ReturnEnv:
    def __init__(self,reference_path=None,dt=.001):
        self.m=next(m for m in motions() if m['name']=='table_tennis_forehand_y+000_z010')
        self.base=TokenReachEnv(model=model(dt,ball_contacts=True),steps=200,point_offset=CONTACT,goal_radius=1.)
        self.model,self.data=self.base.model,self.base.data;self.encoder=MotionEncoder()
        path=reference_path or RETURN_DIR/'forward_reference.npz'
        self.q=np.load(path)['q'];self.dq=np.gradient(self.q,.02,axis=0,edge_order=2)
        self.qa=int(self.model.joint('training_ball_joint').qposadr[0]);self.va=int(self.model.joint('training_ball_joint').dofadr[0])
        self.bg=self.model.geom('training_ball_geom').id;self.fg=self.model.geom('training_face').id;self.tg=self.model.geom('table_top').id;self.ng=self.model.geom('table_net').id
        self.racket={self.fg,self.model.geom('training_handle').id};self.warm=None
        self.reset(np.zeros(9),NOMINAL)
    def point(self):return self.data.geom_xpos[self.fg].copy()
    def normal(self):return self.data.xmat[self.base.wrist].reshape(3,3)[:,1].copy()
    def bp(self):return self.data.qpos[self.qa:self.qa+3].copy()
    def bv(self):return self.data.qvel[self.va:self.va+3].copy()
    def reference(self,times,params):
        lead=params[7]*PARAM_SCALE[7];speed=1+params[8]*PARAM_SCALE[8]
        tt=np.clip(.36+(np.asarray(times)-.36)*speed+lead,0,2.5)
        q=np.stack([np.interp(tt,self.m['time'],self.q[:,j]) for j in range(29)],axis=-1)
        dq=np.stack([np.interp(tt,self.m['time'],self.dq[:,j]) for j in range(29)],axis=-1)*speed
        gate=np.exp(-.5*((tt-1.)/.32)**4);dg=gate*(-2*(tt-1.)**3/.32**4)*speed
        q[...,22:]+=gate[...,None]*params[:7]*PARAM_SCALE[:7]
        dq[...,22:]+=dg[...,None]*params[:7]*PARAM_SCALE[:7]
        limits=self.model.jnt_range[self.model.actuator_trnid[self.base.body_act,0]]
        clipped=(q<limits[:,0]+.01)|(q>limits[:,1]-.01);q=np.clip(q,limits[:,0]+.01,limits[:,1]-.01);dq[clipped]=0
        dq[(np.asarray(times)>.0)&(tt>=2.5)]=0
        return q,dq
    def reset(self,params,case):
        params=np.asarray(params,dtype=float)
        if params.shape!=(9,) or not np.isfinite(params).all() or np.max(abs(params))>1.0001:raise ValueError('Expected bounded nine-dimensional policy action')
        if not -.5<case['y_m']<-.25 or not -3<case['vx_m_s']<-2 or not 1.8<case['vz_m_s']<2.4:raise ValueError('Invalid front serve')
        self.params=params.copy();self.case=dict(case);e=self.base;e.on_substep=None
        if self.warm is None:
            make_env(self.m,existing=e)
            for k in range(68):
                times=k*.02-1+np.arange(10)*.1
                q,dq=self.reference(times,np.zeros(9));e.base_token=self.encoder.encode(q,dq,self.data.xmat[e.pelvis].reshape(3,3).T);e.step(np.zeros(64))
            self.warm=(self.data.qpos.copy(),self.data.qvel.copy(),np.array(e.history),e.last_action.copy())
        qp,qv,h,a=self.warm;mujoco.mj_resetData(self.model,self.data)
        self.data.qpos[:]=qp;self.data.qvel[:]=qv;e.history=deque(h.copy(),maxlen=10);e.last_action=a.copy();e.last_residual=np.zeros(64);e.k=0
        self.data.qpos[self.qa:self.qa+7]=[2.05,case['y_m'],case['z_m'],1,0,0,0];self.data.qvel[self.va:self.va+6]=[case['vx_m_s'],0,case['vz_m_s'],0,0,0]
        mujoco.mj_forward(self.model,self.data)
        self.hit=False;self.crossed=False;self.landed=False;self.failure=None;self.bounces=0;self.events=[];self.last_table=-10
        self.hit_time=None;self.prevpos=self.bp();self.prevvel=self.bv();self.previous_racket=self.point();self.min_dist=10.;self.peak_root=0.;self.peak_leg=0.;self.score=0.;self.k=0;self.frames=[]
        self.out_velocity=None;self.out_position=None;self.net_position=None;self.land_position=None;self.contact_normal=None
        e.on_substep=self.contacts
        return self.observation()
    def observation(self):
        # High-level policy state at serve start; ideal sim ball measurements.
        return np.r_[(self.bp()-[2.05,-.38,1.15])/[.1,.05,.1],(self.bv()-[-2.5,0,2.086])/[.2,1,.2]].astype(np.float32)
    def contacts(self):
        p=self.bp();v=self.bv();t=float(self.data.time)
        for i,c in enumerate(self.data.contact):
            pair=(int(c.geom1),int(c.geom2))
            if self.bg not in pair and not self.racket.intersection(pair):continue
            force=np.zeros(6);mujoco.mj_contactForce(self.model,self.data,i,force)
            if force[0]<1e-5:continue
            if self.bg not in pair:
                if force[0]>1:self.failure=self.failure or 'racket_obstacle';continue
                continue
            other=pair[1] if pair[0]==self.bg else pair[0]
            if other==self.tg:
                if t-self.last_table<.08:continue
                self.last_table=t
                if self.hit:
                    self.land_position=p.tolist()
                    if self.crossed and NET+.02<p[0]<FAR-.02 and abs(p[1])<WIDTH/2-.02:self.landed=True
                    else:self.failure=self.failure or 'wrong_landing'
                else:
                    if NEAR<p[0]<NET and abs(p[1])<WIDTH/2:
                        self.bounces+=1
                        if self.bounces>1:self.failure=self.failure or 'second_bounce'
                    else:self.failure=self.failure or 'invalid_feed'
                self.events.append(dict(type='table',time_s=t,position=p.tolist()))
            elif other==self.fg:
                if abs(float(c.frame[:3]@self.normal()))<.8:self.failure=self.failure or 'racket_rim'
                elif self.bounces!=1:self.failure=self.failure or 'hit_before_bounce'
                elif not self.hit:
                    self.hit=True;self.hit_time=t;self.contact_normal=self.normal().tolist()
                    self.events.append(dict(type='face',time_s=t,position=p.tolist(),velocity_before=self.prevvel.tolist(),normal=self.contact_normal))
            else:self.failure=self.failure or ('net' if other==self.ng else 'ball_obstacle_'+(self.model.geom(other).name or 'unnamed'))
        if self.hit and t>self.hit_time+.035 and self.out_velocity is None:
            self.out_velocity=v.tolist();self.out_position=p.tolist()
        if self.hit and self.prevpos[0]<NET<=p[0] and v[0]>0:
            frac=(NET-self.prevpos[0])/(p[0]-self.prevpos[0]);cross=self.prevpos+frac*(p-self.prevpos)
            self.net_position=cross.tolist()
            if cross[2]>TOP+.1525+.02 and abs(cross[1])<WIDTH/2-.02:self.crossed=True
        self.prevpos=p;self.prevvel=v
    def step(self,record=False):
        previous=(self.hit,self.crossed,self.landed);times=.36+self.k*.02+np.arange(10)*.1
        q,dq=self.reference(times,self.params);e=self.base
        e.base_token=self.encoder.encode(q,dq,self.data.xmat[e.pelvis].reshape(3,3).T);e.step(np.zeros(64));self.k+=1
        p=self.bp();dist=float(np.linalg.norm(p-self.point()));self.min_dist=min(self.min_dist,dist)
        leg=float(np.max(abs(self.data.qpos[e.bqa[:12]]-self.m['dof'][0,:12])));drift=float(np.linalg.norm(self.data.qpos[:2]-self.m['root_pos'][0,:2]))
        self.peak_root=max(self.peak_root,drift);self.peak_leg=max(self.peak_leg,leg)
        unsafe=bool(self.data.qpos[2]<.55 or self.data.xmat[e.pelvis].reshape(3,3)[2,2]<.9 or drift>.1 or leg>.3 or not np.isfinite(self.data.qpos).all())
        if unsafe:self.failure=self.failure or 'posture_limit'
        reward=0.
        if self.hit and not previous[0]:reward+=20
        if self.crossed and not previous[1]:reward+=80
        if self.landed and not previous[2] and not self.failure:reward+=200
        # Sparse return success dominates; shaping just supplies a learning signal before first hits.
        reward-=.005*float(np.mean(self.params[:7]**2))+.02*(leg/.15)**2
        done=bool(self.failure or self.landed or self.k>=125 or p[0]<.12 or p[2]<.10 or abs(p[1])>1.4)
        if done and not self.landed and self.failure is None:
            self.failure='out_of_bounds' if abs(p[1])>1.4 else 'miss' if not self.hit else 'return_missed_table'
        if self.failure:reward-=80 if self.failure in ('posture_limit','racket_obstacle') else 8
        if done:
            if not self.hit:reward+=2*np.exp(-(self.min_dist/.12)**2)
            elif self.out_velocity is not None:
                vx,vy,vz=self.out_velocity
                # Outcome shaping uses the measured post-impact ball velocity,
                # never the reference face angle. It does not declare a return.
                op=np.array(self.out_position);disc=vz*vz+2*9.81*(op[2]-(TOP+.02))
                if vx>0 and disc>=0:
                    flight=(vz+np.sqrt(disc))/9.81;landing=op+np.array([vx,vy,vz])*flight
                    reward+=20*np.exp(-((landing[0]-2.35)/.8)**2-((landing[1]+.15)/.4)**2)
        self.score+=reward
        if record:self.frames.append(dict(time_s=float(self.data.time),phase_s=.36+self.k*.02,qpos=self.data.qpos.tolist(),ball_m=p.tolist(),face_m=self.point().tolist(),face_normal=self.normal().tolist(),hit=self.hit,crossed_net=self.crossed,legal_return=bool(self.landed and not self.failure)))
        return done
    def run(self,params,case,record=False):
        self.reset(params,case)
        for _ in range(125):
            if self.step(record):break
        return self.report()
    def report(self):
        return dict(reward=float(self.score),face_contact=self.hit,crossed_net=self.crossed,legal_return=bool(self.landed and not self.failure),failure=self.failure,
            own_bounces=self.bounces,minimum_miss_cm=100*self.min_dist,hit_time_s=self.hit_time,outgoing_velocity_m_s=self.out_velocity,
            contact_normal=self.contact_normal,net_crossing_m=self.net_position,landing_m=self.land_position,peak_root_cm=100*self.peak_root,
            peak_leg_rad=self.peak_leg,case=self.case,params=self.params.tolist())
